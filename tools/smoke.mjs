import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.GAME_URL || 'http://127.0.0.1:4177';
const output = new URL('../test-results/', import.meta.url).pathname;
await mkdir(output, { recursive: true });
const chrome = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser = await chromium.launch({ headless: true, ...(existsSync(chrome) ? { executablePath: chrome } : {}) });
const failures = [];
const watch = page => {
  page.on('pageerror', e => failures.push(e.message));
  page.on('response', r => { if (r.status() >= 400) failures.push(r.status() + ' ' + r.url()); });
};
const noOverflow = async page => assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Horizontal overflow');
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(); watch(page);
  await page.goto(base); await page.locator('.hero h1').waitFor();
  await page.screenshot({ path: output + 'home-desktop.png', fullPage: true });
  assert.equal(await page.locator('.hero-cards .card').count(), 3);
  await noOverflow(page);
  await page.locator('nav [data-action="rules"]').click();
  assert.equal(await page.locator('.rule').count(), 4);
  await page.keyboard.press('Escape');
  await page.locator('nav [data-action="collection"]').click();
  assert.equal(await page.locator('.collection-item').count(), 24);
  await page.locator('[data-action="filter"][data-id="moon"]').click();
  assert.equal(await page.locator('.collection-item').count(), 6);
  await page.locator('[data-action="filter"][data-id="all"]').click();
  await page.locator('[data-action="toggle-deck"][data-id="chiling"]').click();
  assert.equal(await page.evaluate(() => document.activeElement?.dataset.id), 'chiling');
  assert.equal(await page.locator('[data-action="save-deck"]').isDisabled(), true);
  await page.locator('[data-action="toggle-deck"][data-id="yunya"]').click();
  await page.locator('[data-action="save-deck"]').click();
  await page.locator('.hero h1').waitFor();
  await page.reload();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('shanhai.profile.v3')).deck);
  assert.ok(saved.includes('yunya') && !saved.includes('chiling'));
  await page.locator('.hero [data-action="start"]').click();
  await page.locator('.player-hand .card').first().waitFor();
  assert.equal(await page.locator('.player-hand .card').count(), 4);
  assert.equal(await page.locator('.enemy-hand .card').count(), 4);
  await page.screenshot({ path: output + 'battle-desktop.png', fullPage: true });
  await page.locator('.enemy-hand .card').first().click();
  assert.match(await page.locator('.detail-rank').textContent(), /星/);
  await page.locator('[data-action="close-modal"]').click();
  await page.locator('[data-action="pill-plus"]').focus();
  await page.keyboard.press('Enter');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#pill-amount').textContent(), '2');
  assert.equal(await page.evaluate(() => document.activeElement?.dataset.action), 'pill-plus');
  await page.locator('#pill-slider').fill('12');
  assert.equal(await page.locator('#pill-amount').textContent(), '12');
  await page.locator('[data-action="fury"]').click();
  assert.equal(await page.evaluate(() => document.activeElement?.dataset.action), 'fury');
  assert.equal(await page.locator('#pill-amount').textContent(), '9');
  assert.match(await page.locator('#cost-note').textContent(), /共消耗 12 丹/);
  await page.locator('[data-action="fury"]').click();
  await page.locator('#pill-slider').fill('2');
  let rounds = 0;
  while (rounds < 4) {
    const cards = page.locator('.player-hand .card:not(:disabled)');
    assert.equal(await cards.count(), 4 - rounds);
    await cards.first().click();
    const max = Number(await page.locator('#pill-slider').getAttribute('max'));
    await page.locator('#pill-slider').fill(String(Math.min(rounds === 3 ? max : 2, max)));
    await page.locator('[data-action="commit"]').click();
    await page.locator('.result-modal .resolution').waitFor();
    assert.match(await page.locator('.resolution').textContent(), /受到/);
    rounds++;
    const next = page.locator('[data-action="next-round"]');
    const finished = (await next.textContent()).includes('對局結果');
    if (rounds === 1) await page.screenshot({ path: output + 'reveal-desktop.png', fullPage: true });
    await next.click();
    if (finished) break;
  }
  await page.locator('.match-score').waitFor();
  assert.equal(await page.locator('.history-row').count(), rounds);
  const stats = await page.evaluate(() => JSON.parse(localStorage.getItem('shanhai.profile.v3')).stats);
  assert.equal(stats.played, 1);
  await page.locator('[data-action="end-home"]').click();
  await page.locator('.hero h1').waitFor();
  await context.close();

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1, hasTouch: true, reducedMotion: 'reduce' });
  const phone = await mobile.newPage(); watch(phone);
  await phone.goto(base); await phone.locator('.hero h1').waitFor();
  await noOverflow(phone);
  await phone.screenshot({ path: output + 'home-mobile.png', fullPage: true });
  await phone.locator('.hero [data-action="start"]').click();
  await phone.locator('.player-hand .card').first().waitFor();
  await noOverflow(phone);
  await phone.locator('.player-hand .card').nth(2).click();
  assert.equal(await phone.locator('.player-hand .card').nth(2).getAttribute('aria-pressed'), 'true');
  await phone.locator('[data-action="pill-plus"]').click();
  assert.equal(await phone.locator('#pill-amount').textContent(), '1');
  await phone.screenshot({ path: output + 'battle-mobile.png', fullPage: true });
  await phone.locator('[data-action="commit"]').click();
  await phone.locator('.result-modal').waitFor();
  await noOverflow(phone);
  await phone.screenshot({ path: output + 'reveal-mobile.png', fullPage: true });
  await phone.locator('[data-action="next-round"]').click();
  await phone.locator('.brand').click();
  await phone.locator('[data-action="navigate-confirm"]').click();
  await phone.locator('nav [data-action="collection"]').click();
  await noOverflow(phone);
  await phone.locator('.collection-item .card').first().click();
  assert.equal(await phone.locator('.detail-rank').isVisible(), true);
  await noOverflow(phone);
  await phone.locator('[data-action="close-modal"]').click();
  assert.deepEqual(failures, [], 'Browser/network errors');
  console.log(JSON.stringify({ passed: true, desktopMatchRounds: rounds, checked: ['desktop/mobile rendering', 'rules dialog', '24-card collection and faction filter', '8-card deck validation and persistence', 'pill and Fury budget', 'repeated keyboard controls and preserved focus', 'visible enemy/card-detail star counts', 'public enemy inspection', 'full match and stats', 'mobile card selection and reveal', 'leave-match flow', 'no page/network errors or horizontal overflow'], screenshots: output }, null, 2));
  await mobile.close();
} finally { await browser.close(); }
